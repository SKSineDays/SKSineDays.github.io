/** Generate the public, credential-free website manifest from the preserved selection. */
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const input = new URL('../docs/art-direction/day-photo-provenance.json', import.meta.url);
const output = new URL('../js/day-photo-collection.js', import.meta.url);
const source = JSON.parse(await readFile(input, 'utf8'));
assert.equal(source.days.length, 18);
const selectionBytes = await readFile(new URL('../docs/art-direction/day-photo-selection.json', import.meta.url));
assert.equal(createHash('sha256').update(selectionBytes).digest('hex'), source.selectionSha256);
const selection = JSON.parse(selectionBytes);
const seen = new Set();
const collection = {};
function safeUrl(value, hostname) {
  const url = new URL(value);
  assert.equal(url.protocol, 'https:');
  assert.equal(url.hostname, hostname);
  assert.equal(url.username + url.password, '');
  for (const key of ['client_id', 'access_token', 'secret', 'key']) assert.ok(!url.searchParams.has(key));
  return url;
}
for (let day = 1; day <= 18; day++) {
  const group = source.days[day - 1];
  assert.equal(group.day, day);
  assert.equal(group.photos.length, 10);
  assert.deepEqual(group.photos.map(photo => photo.id), selection[day], `Changed photo IDs/order for day ${day}`);
  collection[day] = group.photos.map(photo => {
    assert.match(photo.id, /^[\w-]+$/);
    assert.ok(!seen.has(photo.id), `Duplicate photo ${photo.id}`);
    seen.add(photo.id);
    assert.ok(photo.width > 0 && photo.height > 0);
    assert.ok(photo.description?.trim().length > 5);
    assert.ok(photo.photographer?.trim());
    const image = safeUrl(photo.imageUrl, 'images.unsplash.com');
    assert.ok(image.searchParams.get('ixid'), `Missing ixid for ${photo.id}`);
    for (const key of ['photoUrl', 'photographerUrl']) {
      const link = safeUrl(photo[key], 'unsplash.com');
      assert.equal(link.searchParams.get('utm_source'), 'sineday');
      assert.equal(link.searchParams.get('utm_medium'), 'referral');
    }
    const download = safeUrl(photo.downloadLocation, 'api.unsplash.com');
    assert.equal(download.pathname, `/photos/${photo.id}/download`);
    assert.ok(download.searchParams.get('ixid'));
    return { id: photo.id, url: photo.imageUrl, alt: photo.description.trim(),
      width: photo.width, height: photo.height, photographer: photo.photographer,
      photographerUrl: photo.photographerUrl, photoUrl: photo.photoUrl };
  });
}
assert.equal(seen.size, 180);
const generated = `// Generated by scripts/generate-day-photo-collection.mjs. Do not hand-edit.\n// All 180 approved photographs, ten per day. No API credentials or visitor tracking.\nexport const DAY_PHOTO_COLLECTION_VERSION = ${JSON.stringify(source.version)};\nconst collection = ${JSON.stringify(collection, null, 2)};\nfor (const photos of Object.values(collection)) {\n  photos.forEach(Object.freeze);\n  Object.freeze(photos);\n}\nexport const DAY_PHOTOS = Object.freeze(collection);\n`;
if (process.argv.includes('--check')) {
  assert.equal(await readFile(output, 'utf8'), generated, 'Run npm run generate:day-photos');
} else await writeFile(output, generated);
console.log('Verified 18 days × 10 photos = 180 unique, attributed Unsplash hotlinks.');
