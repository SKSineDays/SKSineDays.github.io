create or replace function public.globe_stamp_consent() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
  new.updated_at := now();
  if not new.enabled then
    new.region_key := null; new.city_key := null; new.consent_version := null; new.consented_at := null;
  elsif TG_OP = 'INSERT' then
    new.consented_at := now();
  elsif not old.enabled or new.region_key is distinct from old.region_key
     or new.city_key is distinct from old.city_key or new.consent_version is distinct from old.consent_version then
    new.consented_at := now();
  else
    new.consented_at := old.consented_at;
  end if;
  return new;
end;
$$;
revoke all on function public.globe_stamp_consent() from public, anon, authenticated, service_role;

